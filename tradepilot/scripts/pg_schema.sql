-- TradePilot Postgres DDL（M3-①）。
-- 原则：表结构从 SQLite **原样迁走**（docs/production-integration.md 3.5），
-- 不趁迁移改字段语义——迁移是搬运，不是重构；重构进代码 PR 单独审。
--
-- 类型映射（唯一的两处判断）：
--   SQLite REAL        → DOUBLE PRECISION（refresh_tokens.expires_at，秒级 unix 浮点）
--   SQLite INTEGER 0/1 → SMALLINT（disabled/revoked 保持 0/1 直通，不换 BOOLEAN：
--                         换类型就要在导出脚本里转换，转换代码就是新的出错面；
--                         语义改写等真正用上 Postgres 查询后再议）
--   SQLite TEXT（ISO 时间串）→ TEXT：保持 TEXT 而非 TIMESTAMPTZ，理由同上——
--                         现有代码按字符串写入/读取，改类型等于改所有读写代码。
--
-- 本 DDL 已于 2026-11-01 在真实 Postgres 16（docker postgres:16 容器）执行验证：
-- 4 张表建表成功；装载 export_sqlite_to_pg.py 真实导出（18 tenants / 18 users /
-- 20 refresh_tokens / 103 provenance）逐表行数一致；provenance 序列 setval 正确
-- （MAX(id)=103，迁移后新插入得 id=104，不撞主键）；中文（UTF-8）写入读回正常。
-- 验证脚本与流程见 docs/production-integration.md 4.11。

-- ---------- 认证（app/auth.py） ----------

CREATE TABLE IF NOT EXISTS tenants (
    id          TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    company     TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id            TEXT PRIMARY KEY,
    tenant_id     TEXT NOT NULL REFERENCES tenants(id),
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT 'owner',
    disabled      SMALLINT NOT NULL DEFAULT 0,
    created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    token_hash TEXT PRIMARY KEY,        -- 只存 sha256，明文不落库（同 SQLite）
    user_id    TEXT NOT NULL REFERENCES users(id),
    expires_at DOUBLE PRECISION NOT NULL,
    revoked    SMALLINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_refresh_user ON refresh_tokens(user_id);

-- ---------- 存证（app/provenance.py） ----------

-- GENERATED BY DEFAULT AS IDENTITY：导出的数据带显式 id，装载后需
-- setval 把序列拨到 max(id)（导出脚本会自动附上），否则新写入撞主键。
CREATE TABLE IF NOT EXISTS provenance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL,          -- page / item / price / policy
    url          TEXT NOT NULL,
    fetched_at   TEXT NOT NULL,
    content_hash TEXT NOT NULL,
    payload      TEXT NOT NULL           -- JSON：该数据点的真实字段
);
CREATE INDEX IF NOT EXISTS idx_provenance_kind ON provenance(kind);
